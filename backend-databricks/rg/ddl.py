def migrate() -> list[str]:
    """Add columns introduced after the first release to tables that already exist."""
    have = {(r["table_name"], r["column_name"]) for r in db.query(
        "SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = current_schema()")}
    tables = {t for t, _ in have}
    added = []
    for table, column, stmt in MIGRATIONS:
        if table in tables and (table, column.lower()) not in have:
            db.execute(stmt)
            added.append(f"{table}.{column}")
    return added


def init_schema() -> list[str]:
    """Create this app's own Postgres schema (if missing) and any rg_ tables not yet in it. Returns
    the table names created. The schema must exist before current_schema() resolves to it (see
    rg/db.py's _conninfo() - search_path falls back to 'public' until this runs once)."""
    db.execute(f"CREATE SCHEMA IF NOT EXISTS {config.PG_SCHEMA}")
    db.execute("CREATE EXTENSION IF NOT EXISTS vector")  # needed before any VECTOR(n) column below
    have = {r["table_name"] for r in db.query(
        "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema()")}
    created = []
    for name, stmt in TABLES.items():
        if name not in have:
            db.execute(stmt)
            if name in dict(VECTOR_INDEXES):
                db.execute(dict(VECTOR_INDEXES)[name])
            created.append(name)
    return created
